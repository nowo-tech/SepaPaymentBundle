<?php

declare(strict_types=1);

namespace Nowo\SepaPaymentBundle\Tests\Integration;

use Nowo\SepaPaymentBundle\Generator\DirectDebitGenerator;
use Nowo\SepaPaymentBundle\Generator\DirectDebitGeneratorInterface;
use Nowo\SepaPaymentBundle\Lookup\BicLookupService;
use Nowo\SepaPaymentBundle\Model\DirectDebit\DirectDebitGenerationOptions;
use Nowo\SepaPaymentBundle\Model\DirectDebit\Pain008Version;
use Nowo\SepaPaymentBundle\Model\DirectDebit\SequenceTypeMode;
use Nowo\SepaPaymentBundle\Tests\Fixtures\Bc\DirectDebitBcCases;
use Nowo\SepaPaymentBundle\Tests\Kernel\TestKernel;
use Nowo\SepaPaymentBundle\Validator\IbanValidator;
use PHPUnit\Framework\Attributes\DataProvider;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;

use function array_keys;
use function count;
use function dirname;
use function file_get_contents;
use function glob;

/**
 * BC proof for 2.2.0: with the default configuration, two-decimal input written with the 2.1 API produces XML that is
 * byte-identical to 2.1.0 (pain.008.001.09). The golden files in tests/Fixtures/Bc/golden-2.1.0 were generated by the
 * v2.1.0 sources from {@see DirectDebitBcCases}; only GrpHdr/CreDtTm ("now") is normalised.
 *
 * @author Héctor Franco Aceituno <hectorfranco@nowo.tech>
 * @copyright 2026 Nowo.tech
 */
final class DirectDebitBackwardCompatibilityTest extends KernelTestCase
{
    protected static function getKernelClass(): string
    {
        return TestKernel::class;
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function caseProvider(): iterable
    {
        foreach (array_keys(DirectDebitBcCases::objectCases() + DirectDebitBcCases::arrayCases()) as $name) {
            yield $name => [$name];
        }
    }

    /**
     * Every golden file has a case, and every case a golden file.
     */
    public function testEveryCaseHasAGoldenFile(): void
    {
        $files = glob(self::goldenDirectory() . '/*.xml') ?: [];
        $this->assertCount(count(DirectDebitBcCases::objectCases()) + count(DirectDebitBcCases::arrayCases()), $files);
    }

    /**
     * The generator built by the bundle container with the default configuration writes the 2.1.0 bytes.
     */
    #[DataProvider('caseProvider')]
    public function testDefaultContainerGeneratorIsByteIdenticalTo210(string $name): void
    {
        self::bootKernel();
        $generator = self::getContainer()->get(DirectDebitGenerator::SERVICE_NAME);
        $this->assertInstanceOf(DirectDebitGenerator::class, $generator);

        $this->assertSame(self::golden($name), DirectDebitBcCases::normalise(self::generate($generator, $name, null)));
    }

    /**
     * The same generator built by hand (as the golden files were) writes the 2.1.0 bytes, also when the per-call options
     * restate the defaults.
     */
    #[DataProvider('caseProvider')]
    public function testHandBuiltGeneratorIsByteIdenticalTo210(string $name): void
    {
        $generator = new DirectDebitGenerator(new IbanValidator(), null, false, null, null, new BicLookupService(new IbanValidator()));

        $this->assertSame(self::golden($name), DirectDebitBcCases::normalise(self::generate($generator, $name, null)));
        $this->assertSame(self::golden($name), DirectDebitBcCases::normalise(self::generate($generator, $name, new DirectDebitGenerationOptions(Pain008Version::V09, SequenceTypeMode::PER_TRANSACTION))));
    }

    private static function generate(DirectDebitGeneratorInterface $generator, string $name, ?DirectDebitGenerationOptions $options): string
    {
        $objects = DirectDebitBcCases::objectCases();
        if (isset($objects[$name])) {
            return $generator->generate($objects[$name], $options);
        }

        return $generator->generateFromArray(DirectDebitBcCases::arrayCases()[$name], $options);
    }

    private static function golden(string $name): string
    {
        return (string) file_get_contents(self::goldenDirectory() . '/' . $name . '.xml');
    }

    private static function goldenDirectory(): string
    {
        return dirname(__DIR__) . '/Fixtures/Bc/golden-2.1.0';
    }
}
